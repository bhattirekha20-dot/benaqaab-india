RATE = "+10%"  # Natural documentary cadence (~155 words/min)

async def generate_full_narration():
    print(f"🎙️ Generating Episode EP-19 Voiceover using {VOICE} at rate {RATE}...")
    full_text = " ".join([c["text"] for c in CHAPTER_SCRIPTS])
    print(f"📝 Total Script Characters: {len(full_text)}, Chapters: {len(CHAPTER_SCRIPTS)}")

    comm = edge_tts.Communicate(full_text, VOICE, rate=RATE, pitch="+0Hz")

    boundaries = []
    with open(OUTPUT_RAW_MP3, "wb") as f:
        async for chunk in comm.stream():
            if chunk["type"] == "audio":
                f.write(chunk["data"])
            elif chunk["type"] in ("WordBoundary", "SentenceBoundary"):
                boundaries.append({
                    "type": chunk["type"],
                    "offset": chunk["offset"] / 10_000_000,
                    "duration": chunk["duration"] / 10_000_000,
                    "text": chunk.get("text", "")
                })

    print(f"✅ Raw audio generated: {OUTPUT_RAW_MP3}")
    print(f"📊 Captured {len(boundaries)} word/sentence boundaries.")

    # Mastering with FFmpeg: Volume boost + Loudnorm to -14 LUFS (true peak -1.0 dBFS)
    print("🎛️ Mastering audio to broadcast standard -14 LUFS using FFmpeg...")
    cmd = [
        "ffmpeg", "-y",
        "-i", str(OUTPUT_RAW_MP3),
        "-filter_complex",
        "[0:a]volume=1.30,loudnorm=I=-14:LRA=7:TP=-1.0[out]",
        "-map", "[out]",
        "-c:a", "libmp3lame",
        "-b:a", "320k",
        "-threads", "0",
        str(MASTER_MP3)
    ]
    subprocess.run(cmd, check=True)

    # Get exact duration via ffprobe
    probe = subprocess.run([
        "ffprobe", "-v", "error", "-show_entries", "format=duration",
        "-of", "default=noprint_wrappers=1:nokey=1", str(MASTER_MP3)
    ], capture_output=True, text=True)
    duration = float(probe.stdout.strip() or 0)
    print(f"⏱️ Master Audio Duration: {duration:.2f} seconds ({duration/60:.2f} minutes)")

    # Save word timestamps & metadata
    with open(TIMESTAMPS_JSON, "w", encoding="utf-8") as f:
        json.dump({
            "episode": "EP-19",
            "voice": VOICE,
            "rate": RATE,
            "duration": duration,
            "chapters": CHAPTER_SCRIPTS,
            "boundaries": boundaries
        }, f, indent=2, ensure_ascii=False)

    print(f"💾 Saved metadata to: {TIMESTAMPS_JSON}")

if __name__ == "__main__":
    asyncio.run(generate_full_narration())
